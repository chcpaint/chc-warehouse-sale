-- 072_item_requests.sql
--
-- Item requests: one place for "can you get us X?" -- instead of emails, texts,
-- phone calls and paper on a desk. Every customer has an "Item requests" screen
-- in its store; CHC staff can also enter a request for a customer who called or
-- emailed. Each new request emails the distributor's request inbox (a list CHC
-- keeps in the console, so someone else can cover). Staff close a request as
-- Complete (it's on the customer's list -- they are emailed that it's ready to
-- order) or Can't supply (they are emailed the reason).
--
-- Nothing here changes how any company signs in. Safe to re-run.
-- Run in the Supabase SQL editor BEFORE deploying the code.

CREATE TABLE IF NOT EXISTS public.item_requests (
    id                   uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    request_no           bigint GENERATED BY DEFAULT AS IDENTITY,
    company_id           uuid NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
    location_id          uuid REFERENCES public.company_locations(id) ON DELETE SET NULL,
    status               text NOT NULL DEFAULT 'open',

    -- What they asked for
    item_name            text NOT NULL,
    part_number          text,
    brand                text,
    quantity             text,
    notes                text,
    photos               jsonb NOT NULL DEFAULT '[]'::jsonb,   -- [{ path, mime, bytes }] in the private bucket

    -- Who asked, and how it reached CHC
    requested_by_name    text,
    requested_by_email   text,
    requested_by_user_id uuid,
    source               text NOT NULL DEFAULT 'store',       -- store | staff
    received_via         text,                                -- staff-entered: phone | email | text | in_person | other
    entered_by_admin_id  uuid,
    entered_by_name      text,

    -- How it was closed
    product_id           uuid REFERENCES public.products(id) ON DELETE SET NULL,
    staff_note           text,
    closed_at            timestamptz,
    closed_by_admin_id   uuid,
    closed_by_name       text,
    customer_notified_at timestamptz,

    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT item_requests_status_chk   CHECK (status IN ('open', 'complete', 'cannot_supply')),
    CONSTRAINT item_requests_source_chk   CHECK (source IN ('store', 'staff')),
    CONSTRAINT item_requests_via_chk      CHECK (received_via IS NULL OR received_via IN ('phone', 'email', 'text', 'in_person', 'other')),
    CONSTRAINT item_requests_name_chk     CHECK (char_length(item_name) BETWEEN 1 AND 200),
    CONSTRAINT item_requests_notes_chk    CHECK (notes IS NULL OR char_length(notes) <= 2000),
    CONSTRAINT item_requests_staffnote_chk CHECK (staff_note IS NULL OR char_length(staff_note) <= 1000),
    CONSTRAINT item_requests_photos_chk   CHECK (jsonb_typeof(photos) = 'array' AND jsonb_array_length(photos) <= 3)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_item_requests_no ON public.item_requests (request_no);
CREATE INDEX IF NOT EXISTS idx_item_requests_company ON public.item_requests (company_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_item_requests_open ON public.item_requests (created_at DESC) WHERE status = 'open';

-- Photos: a PRIVATE bucket. The app hands out short-lived signed links; nothing
-- in it is reachable by a guessed URL.
-- Images only, 5 MB each: the bucket refuses anything else even if the
-- server's own check were ever bypassed (same defence as migration 061).
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES ('item-request-photos', 'item-request-photos', false, 5242880,
        ARRAY['image/png','image/jpeg','image/gif','image/webp'])
ON CONFLICT (id) DO UPDATE
   SET public = false,
       file_size_limit = EXCLUDED.file_size_limit,
       allowed_mime_types = EXCLUDED.allowed_mime_types;

-- Who is emailed about new requests: kept on the distributor, changed in the
-- console. CHC starts with Adam; anyone covering can be added there.
UPDATE public.distributors
SET settings = jsonb_set(coalesce(settings, '{}'::jsonb), '{item_requests}',
                         '{"notify_emails": ["adam@chcpaint.com"]}'::jsonb, true)
WHERE is_default = true
  AND (settings -> 'item_requests') IS NULL;

ALTER TABLE public.item_requests ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.item_requests FROM anon, authenticated;

